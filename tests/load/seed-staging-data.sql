-- Safety:
--   Intended ONLY for disposable staging containers (egitim-k6-staging).
--   Reuses the PBKDF2 PasswordHash generated by --initialize-platform for the
--   disposable bootstrap user so no hardcoded credentials or secrets are stored.
-- =============================================================================

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
