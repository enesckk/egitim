-- 1. Extract valid PBKDF2 password hash from disposable bootstrap account
DECLARE @PasswordHash NVARCHAR(MAX);
DECLARE @SecurityStamp NVARCHAR(MAX);

SELECT TOP 1
    @PasswordHash = PasswordHash,
    @SecurityStamp = SecurityStamp
FROM AspNetUsers
WHERE PasswordHash IS NOT NULL;

IF @PasswordHash IS NULL
BEGIN
    RAISERROR('No initialized bootstrap user found in AspNetUsers. Run --initialize-platform first.', 16, 1);
    ROLLBACK TRANSACTION;
    RETURN;
END

