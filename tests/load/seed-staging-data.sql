-- 11. Seed 6 Published Exams, 24 ExamSections, and 630 Finalized StudentExamAttempts
DECLARE @e INT = 1;
WHILE @e <= 6
BEGIN
    DECLARE @ExamId UNIQUEIDENTIFIER = CAST(
        '66000000-0000-0000-0020-' + RIGHT('000000000000' + CAST(@e AS VARCHAR(12)), 12)
        AS UNIQUEIDENTIFIER);
    DECLARE @SecMat UNIQUEIDENTIFIER = CAST(
        '66000000-0000-0021-0001-' + RIGHT('000000000000' + CAST(@e AS VARCHAR(12)), 12)
        AS UNIQUEIDENTIFIER);
    DECLARE @SecTur UNIQUEIDENTIFIER = CAST(
        '66000000-0000-0021-0002-' + RIGHT('000000000000' + CAST(@e AS VARCHAR(12)), 12)
        AS UNIQUEIDENTIFIER);
    DECLARE @SecFiz UNIQUEIDENTIFIER = CAST(
