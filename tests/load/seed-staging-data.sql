        AS UNIQUEIDENTIFIER);
    DECLARE @ExamDate DATETIMEOFFSET = DATEADD(DAY, -7 * (7 - @e), @Now);

    IF NOT EXISTS (SELECT 1 FROM Exams WHERE Id = @ExamId)
    BEGIN
        INSERT INTO Exams (
            Id, InstitutionId, ExamTypeId, Code, Title, ExamDate,
            Status, ScoreSource, WrongAnswerPenalty, CreatedAt, IsDeleted
        )
        VALUES (
            @ExamId, @InstId, @ExamTypeId,
            N'TYT-K6-0' + CAST(@e AS NVARCHAR(10)),
            N'Staging TYT Deneme ' + CAST(@e AS NVARCHAR(10)),
            @ExamDate, 1, 0, 4.00, @Now, 0
        );

        INSERT INTO ExamSections (Id, InstitutionId, ExamId, SubjectId, DisplayOrder, QuestionCount, CreatedAt, IsDeleted) VALUES
        (@SecTur, @InstId, @ExamId, @SubTur, 1, 20, @Now, 0),
        (@SecMat, @InstId, @ExamId, @SubMat, 2, 20, @Now, 0),
        (@SecFiz, @InstId, @ExamId, @SubFiz, 3, 10, @Now, 0),
        (@SecKim, @InstId, @ExamId, @SubKim, 4, 10, @Now, 0);

        -- Bulk-insert 105 student attempts for this exam
        DECLARE @st INT = 1;
        WHILE @st <= 105
        BEGIN
            DECLARE @StId UNIQUEIDENTIFIER = CAST(
                '66000000-0000-0000-0001-' + RIGHT('000000000000' + CAST(@st AS VARCHAR(12)), 12)
                AS UNIQUEIDENTIFIER);
            DECLARE @AttId UNIQUEIDENTIFIER = CAST(
                '66000000-0000-0022-' + RIGHT('0000' + CAST(@e AS VARCHAR(4)), 4) + '-' + RIGHT('000000000000' + CAST(@st AS VARCHAR(12)), 12)
                AS UNIQUEIDENTIFIER);

            DECLARE @MatC INT = 10 + ((@st + @e) % 8);
            DECLARE @MatW INT = 20 - @MatC;
            DECLARE @TurC INT = 12 + ((@st + @e) % 6);
            DECLARE @TurW INT = 20 - @TurC;
            DECLARE @FizC INT = 5 + ((@st + @e) % 4);
            DECLARE @FizW INT = 10 - @FizC;
            DECLARE @KimC INT = 6 + ((@st + @e) % 3);
            DECLARE @KimW INT = 10 - @KimC;

            DECLARE @TotC INT = @MatC + @TurC + @FizC + @KimC;
            DECLARE @TotW INT = @MatW + @TurW + @FizW + @KimW;
            DECLARE @TotNet DECIMAL(7,2) = @TotC - (@TotW / 4.0);

            INSERT INTO StudentExamAttempts (
                Id, InstitutionId, ExamId, StudentId, AttemptNumber, TakenAt,
                Status, ScoreSource, FinalizedAt, IsRawAvailable,
                TotalCorrect, TotalWrong, TotalBlank, TotalNet, ReportedScore,
                CreatedAt, IsDeleted
            )
            VALUES (
                @AttId, @InstId, @ExamId, @StId, 1, @ExamDate,
                1, 0, DATEADD(HOUR, 2, @ExamDate), 0,
                @TotC, @TotW, 0, @TotNet, 250.0 + (@TotNet * 3.5),
                @Now, 0
            );

            INSERT INTO StudentExamSubjectResults (
                Id, InstitutionId, StudentExamAttemptId, ExamSectionId,
                Correct, Wrong, Blank, Net, CreatedAt, IsDeleted
            )
